// 文章中のカラー絵文字 → モノクロアイコン(ヘルプ文など、文字列のまま持っている説明文用)
const EMOJI_TO_ICON: Record<string, NoteIconName> = {
  '🔒': 'lock', '🌐': 'globe', '🛡': 'shield', '👥': 'users', '👤': 'user',
  '📁': 'folder', '📂': 'folder-open', '📥': 'inbox',
  '📝': 'file-text', '📄': 'copy', '📋': 'clipboard',
  '📣': 'megaphone', '📓': 'book', '📖': 'book-open', '❓': 'help',
  '📎': 'paperclip', '✏': 'pencil', '✅': 'check-circle', '⚠': 'warning',
  '🛠': 'wrench', '🖼': 'image', '⏳': 'clock',
};
const EMOJI_RE = new RegExp(`(${Object.keys(EMOJI_TO_ICON).join('|')})\\uFE0F?`, 'g');

/** 文字列に含まれるカラー絵文字を、モノクロアイコンに置き換えた表示用ノードにする */
export function withNoteIcons(text: string): React.ReactNode {
  const out: React.ReactNode[] = [];
  let last = 0;
  let m: RegExpExecArray | null;
  EMOJI_RE.lastIndex = 0;
  while ((m = EMOJI_RE.exec(text))) {
    if (m.index > last) out.push(text.slice(last, m.index));
    out.push(<NoteIcon key={`${m.index}`} name={EMOJI_TO_ICON[m[1]]} />);
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push(text.slice(last));
  return <>{out}</>;
}
